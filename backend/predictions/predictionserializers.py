from rest_framework import serializers

class predictionserializer(serializers.Serializer):
    product_category = serializers.CharField(max_length = 50)
    product_price = serializers.FloatField()
    discount_percent = serializers.FloatField(allow_null = True, required = False)
    review_count = serializers.IntegerField(allow_null = True, required = False)
    fragile_item = serializers.BooleanField(allow_null = True, required = False)
    sub_category = serializers.CharField(max_length = 50)
    product_rating = serializers.FloatField(allow_null = True, required = False)
    quantity = serializers.IntegerField(allow_null = True, required = False)
    brand = serializers.CharField()
    warranty_available = serializers.BooleanField(allow_null = True, required = False)
    product_return_rate = serializers.FloatField(allow_null = True, required = False)
    brand_return_rate = serializers.FloatField(allow_null = True, required = False)
    category_return_rate = serializers.FloatField(allow_null = True, required = False)
    defect_rate = serializers.FloatField(allow_null = True, required = False)
    seller_rating = serializers.FloatField(allow_null = True, required = False)
    seller_return_rate = serializers.FloatField(allow_null = True, required = False)
    fulfillment_type = serializers.CharField()
    shipping_distance_km = serializers.FloatField(allow_null = True, required = False)
    delayed_delivery = serializers.BooleanField(allow_null = True, required = False)
    payment_method = serializers.CharField()
    product_page_views = serializers.IntegerField(allow_null = True, required = False)
    chat_messages = serializers.IntegerField(allow_null = True, required = False)
    wishlist_before_purchase = serializers.BooleanField(allow_null = True, required = False)
    support_calls = serializers.IntegerField(allow_null = True, required = False)